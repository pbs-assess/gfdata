SELECT
  DATABASE_NAME,
  MC.TRIP_ID,
  MC.FISHING_EVENT_ID,
  FISHERY_SECTOR,
  TRIP_CATEGORY,
  GEAR,
  BEST_DATE,
  FE_START_DATE,
  FE_END_DATE,
  LAT,
  LON,
  BEST_DEPTH,
  MC.SPECIES_CODE,
  MC.DFO_STAT_AREA_CODE,
  MC.DFO_STAT_SUBAREA_CODE,
  SPECIES_SCIENTIFIC_NAME,
  SPECIES_COMMON_NAME,
  LANDED_KG,
  CASE WHEN GEAR IN ('TRAP', 'HOOK AND LINE', 'MIDWATER TRAWL') AND YEAR(BEST_DATE) < 2006 THEN 0
	WHEN GEAR IN ('BOTTOM TRAWL', 'UNKNOWN TRAWL') AND YEAR(BEST_DATE) <1996 THEN 0
	-- WHEN TRIP_CATEGORY IN ('OPT B') AND YEAR(BEST_DATE) <2006 THEN 0
	ELSE DISCARDED_KG END AS DISCARDED_KG,
  LANDED_PCS,
  DISCARDED_PCS,
  SUBLEGAL_RELEASED_COUNT,
  LEGAL_RELEASED_COUNT,
  SUBLEGAL_LICED_COUNT,
  LEGAL_LICED_COUNT,
  SUBLEGAL_BAIT_COUNT,
  LEGAL_BAIT_COUNT,
  MC.MAJOR_STAT_AREA_CODE,
  MC.MINOR_STAT_AREA_CODE,
	MSA.MAJOR_STAT_AREA_NAME,
  LOCALITY_CODE,
  VESSEL_NAME,
  VESSEL_REGISTRATION_NUMBER
FROM GFFOS.dbo.GF_MERGED_CATCH MC
	INNER JOIN GFFOS.dbo.SPECIES SP ON SP.SPECIES_CODE = MC.SPECIES_CODE
	INNER JOIN GFBioSQL.dbo.MAJOR_STAT_AREA MSA ON MC.MAJOR_STAT_AREA_CODE = MSA.MAJOR_STAT_AREA_CODE
	LEFT JOIN (SELECT
		TRIP_ID
		,TRIP_CATEGORY
		,FISHING_EVENT_ID
		,LAT
		,LON
	FROM GFFOS.dbo.GF_D_OFFICIAL_FE_CATCH
		GROUP BY TRIP_ID, TRIP_CATEGORY, FISHING_EVENT_ID, LAT, LON) C ON CAST (MC.TRIP_ID AS VARCHAR) = CAST (C.TRIP_ID AS VARCHAR) AND MC.FISHING_EVENT_ID = C.FISHING_EVENT_ID
	LEFT JOIN (SELECT
		TRIP_ID
		,FISHING_EVENT_ID
		,SPECIES_CODE
		,SUM(SUBLEGAL_RELEASED_COUNT) AS SUBLEGAL_RELEASED_COUNT
		,SUM(LEGAL_RELEASED_COUNT) AS LEGAL_RELEASED_COUNT
		,SUM(SUBLEGAL_LICED_COUNT) AS SUBLEGAL_LICED_COUNT
		,SUM(LEGAL_LICED_COUNT) AS LEGAL_LICED_COUNT
		,SUM(SUBLEGAL_BAIT_COUNT) AS SUBLEGAL_BAIT_COUNT
		,SUM(LEGAL_BAIT_COUNT) AS LEGAL_BAIT_COUNT
	FROM GFFOS.dbo.GF_D_OFFICIAL_FE_CATCH
		GROUP BY TRIP_ID, FISHING_EVENT_ID, SPECIES_CODE) CC ON CAST (MC.TRIP_ID AS VARCHAR) = CAST (CC.TRIP_ID AS VARCHAR) AND MC.FISHING_EVENT_ID = CC.FISHING_EVENT_ID AND MC.SPECIES_CODE = CC.SPECIES_CODE
-- insert species here
-- insert major here
ORDER BY BEST_DATE, SPECIES_COMMON_NAME

